def _stamp(second: int) -> str:
    """Return one ISO-8601 instant ``second`` seconds into the fixture session."""
    return f"2026-05-01T10:00:{second:02d}.000Z"


def _claude(
    kind: str,
    second: int,
    content: object,
    *,
    uuid: str,
    session: str = _SESSION,
    message_id: str | None = None,
    **extra: object,
) -> JsonObject:
    """Build one Claude Code transcript record with Anthropic-style content."""
    message: dict[str, object] = {"role": kind, "content": content}
    if kind == "assistant":
        message.update(
            {
                "id": message_id or f"msg-{uuid}",
                "model": "claude-test",
                "usage": {"input_tokens": 10, "output_tokens": 5, "cache_read_input_tokens": 2},
            }
        )
    record: dict[str, object] = {
        "type": kind,
        "uuid": uuid,
        "parentUuid": None,
        "sessionId": session,
        "timestamp": _stamp(second),
        "isSidechain": False,
        "cwd": "/home/alice/project",
        "gitBranch": "main",
        "version": "2.1.0",
        "message": message,
    }
    record.update(extra)
    return json.loads(json.dumps(record))


