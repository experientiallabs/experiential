def test_trace_identity_is_deterministic_across_file_and_directory_inputs(tmp_path: Path) -> None:
    """Loading a file or its directory, repeatedly, yields the same trace identities."""
    path = _write(tmp_path / "ds" / "chat.jsonl", _claude_records())

    from_file = load_agent_sessions(path)
    from_directory = load_agent_sessions(path.parent)

    assert [trace.trace_id for trace in from_file.traces] == [
        trace.trace_id for trace in from_directory.traces
    ]
    assert from_file.traces == load_agent_sessions(path).traces
    assert len({trace.trace_id for trace in from_file.traces}) == 3
    labelled = load_agent_sessions(path, source_id="hub/claude")
    assert labelled.traces[0].source.identity.source_id == "hub/claude"
    assert {trace.trace_id for trace in labelled.traces}.isdisjoint(
        trace.trace_id for trace in from_file.traces
    )


def test_directory_import_retains_every_exclusion(tmp_path: Path) -> None:
    """Malformed lines, foreign files, and prompt-free sessions are explicit issues."""
    _write(tmp_path / "ds" / "a" / "chat.jsonl", _claude_records())
    _write(tmp_path / "ds" / "pi.jsonl", _pi_records())
    _write(tmp_path / "ds" / "labels.jsonl", [{"trace_id": "x", "quality": 1}])
    broken = tmp_path / "ds" / "broken.jsonl"
    broken.write_text(
        json.dumps(_claude("assistant", 1, [{"type": "text", "text": "hi"}], uuid="z1"))
        + "\n{not json\n",
        encoding="utf-8",
    )
    (tmp_path / "ds" / "README.md").write_text("not a session", encoding="utf-8")

    result = load_agent_sessions(tmp_path / "ds")

    assert len(result.traces) == 4
    reasons = {issue.source_record: issue.message for issue in result.issues}
    assert reasons["broken.jsonl:line-2"] == "invalid JSON record"
    assert "not a recognized agent session file" in reasons["file-labels.jsonl"]
    assert reasons[f"session-ds/broken.jsonl#{_SESSION}"] == "session has no user prompt"
    assert result.source is not None and result.source.sha256 is not None


def test_missing_or_empty_inputs_fail_with_guidance(tmp_path: Path) -> None:
    """A missing path or a directory without session files raises an actionable error."""
    with pytest.raises(VendorTraceFormatError, match="pass a session file or a directory"):
        load_agent_sessions(tmp_path / "absent")
