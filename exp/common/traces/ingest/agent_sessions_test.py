def test_registered_source_streams_identically_and_is_detected(tmp_path: Path) -> None:
    """The shared source table, detection, and streaming import agree on one session file."""
    path = _write(tmp_path / "ds" / "chat.jsonl", _claude_records())
    pi_path = _write(tmp_path / "ds" / "pi.jsonl", _pi_records())
    export_path = _write(tmp_path / "ds" / "export.jsonl", [_export_record()])

    expected = load_trace_source(AGENT_SESSIONS_VENDOR, path)
    summary, receipt = ingest_traces(
        "sessions", root=tmp_path / "state", source_format=AGENT_SESSIONS_VENDOR, path=path
    )

    assert receipt is not None
    assert summary.trace_count == 3
    assert read_ingested_traces(tmp_path / "state", receipt.import_id) == expected
    assert [detect_trace_source(item) for item in (path, pi_path, export_path)] == [
        AGENT_SESSIONS_VENDOR
    ] * 3


