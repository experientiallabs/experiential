def _write(path: Path, records: Sequence[JsonObject]) -> Path:
    """Write records as JSONL and return the file path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(json.dumps(record) for record in records) + "\n", encoding="utf-8")
    return path


def _metadata(trace: Trace) -> JsonObject:
    """Return the trace metadata recorded on the first span."""
    metadata = trace.spans[0].attributes["exp.trace.metadata"]
    assert isinstance(metadata, dict)
    return metadata


def _calls(trace: Trace) -> list[TraceSpan]:
    """Return the model spans that request a tool."""
    return [
        span
        for span in trace.spans
        if span.name == "agent.model_call" and "gen_ai.tool.name" in span.attributes
    ]


def _results(trace: Trace) -> list[TraceSpan]:
    """Return the tool-result spans."""
    return [span for span in trace.spans if span.name == "agent.tool_call"]


def _by_task(traces: Sequence[Trace]) -> dict[str, Trace]:
    """Index traces by their task text."""
    return {trace.task: trace for trace in traces}


def test_claude_code_sessions_subagents_and_tool_pairing(tmp_path: Path) -> None:
    """A multi-session file yields one trace per session and subagent, with paired tools."""
    result = load_agent_sessions(_write(tmp_path / "ds" / "chat.jsonl", _claude_records()))

    assert result.issues == ()
    traces = _by_task(result.traces)
    assert set(traces) == {
        "Fix the failing test. My key is [REDACTED]",
        "Explore the repo",
        "Say hello",
    }
    main = traces["Fix the failing test. My key is [REDACTED]"]
    sub = traces["Explore the repo"]
    assert main.conversation_id == sub.conversation_id == f"ds#{_SESSION}"
    assert traces["Say hello"].conversation_id == "ds#other-session"
    assert main.initial_context == {
        "instruction_messages": [
            {
                "role": "user",
                "content": (
                    "<local-command-caveat>Caveat: generated by local commands."
                    "</local-command-caveat>"
                ),
            }
        ]
    }
    calls = _calls(main)
    assert [span.attributes["gen_ai.tool.name"] for span in calls] == ["Read", "Bash"]
    assert calls[0].attributes["gen_ai.completion"] == "Reading."
    assert calls[0].attributes["gen_ai.tool.call.arguments"] == (
        '{"file_path":"/home/[USER]/project/app.py"}'
    )
    results = _results(main)
    assert [span.parent_span_id for span in results] == [span.span_id for span in calls]
    assert [span.attributes["gen_ai.tool.call.id"] for span in results] == [
        "toolu_read",
        "toolu_bash",
    ]
    assert [span.attributes["gen_ai.tool.is_error"] for span in results] == [False, True]
    assert results[1].attributes["gen_ai.tool.message"] == "1 failed"
    assert all(span.failure is None for span in main.spans)
    assert main.outcome is None
    assert {tool.name for tool in main.tools} == {"Bash", "Read"}
    assert calls[0].model is None
    assert calls[0].attributes["gen_ai.request.model"] == "claude-test"
    assert calls[0].usage is not None and calls[0].usage.cached_input_tokens == 2
    metadata = _metadata(main)
    assert metadata["cwd"] == "/home/[USER]/project"
    assert metadata["ai-title"] == "Fix failing test"
    assert metadata["sidechain"] is False
    assert _metadata(sub)["sidechain"] is True
    assert _metadata(sub)["agent_id"] == "sub1"
    redaction = metadata["redaction"]
    assert isinstance(redaction, dict)
    assert redaction["policy"] == "agent-sessions-redaction-v1"
    assert redaction["secret_replacements"] == 1
    assert redaction["home_path_replacements"] >= 2
    serialized = json.dumps([trace.model_dump(mode="json") for trace in result.traces])
    assert _SECRET not in serialized and "alice" not in serialized


def test_claude_code_spans_pair_with_real_transitions_and_contracts(tmp_path: Path) -> None:
    """Imported spans give exact action/reply transitions and tool contracts."""
    result = load_agent_sessions(_write(tmp_path / "ds" / "chat.jsonl", _claude_records()))
    main = _by_task(result.traces)["Fix the failing test. My key is [REDACTED]"]
    binding = RAGLineageBinding(trace_id=main.trace_id, lineage_id="lineage-main", partition="fit")

    transitions = extract_real_transitions(
        (main,), (binding,), included_partitions=frozenset({"fit"})
    )

    tool_replies = {
        item.action.tool_name: item.observation.content
        for item in transitions
        if item.action.kind == "tool_call"
    }
    assert tool_replies == {"Read": "def test(): fail", "Bash": "1 failed"}
    messages = [item for item in transitions if item.action.kind == "message"]
    assert [(item.action.content, item.observation.content) for item in messages] == [
        ("Fixed the test.", "Thanks, now run it again")
    ]
    contracts = parse_tool_contracts(result.traces)
    assert set(contracts) == {"Bash", "Grep", "Read"}
    assert contracts["Bash"].failures == 1
    assert contracts["Bash"].error_forms == ("tool_error: 1 failed",)
    assert contracts["Read"].argument_types == {"file_path": ("string",)}


